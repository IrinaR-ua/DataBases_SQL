-- 1.  Расчет площади круга
-- Создайте функцию для расчета площади круга, если известен его радиус.
-- Используйте формулу 
-- Где:
-- S — площадь шара,
-- r — радиус шара,
​-- π≈3.14159, используйте функцию PI(), которая возвращает это число

-- S круга = πr2   

-- В ЗАДАНИИ НА ПЛАТФОРМЕ ОШИБКА (ПЕРЕПУТАН КРУГ/ШАР)

DELIMITER //
CREATE FUNCTION sqr_circle(r DECIMAL(5, 2))
RETURNS DECIMAL
DETERMINISTIC
BEGIN 
	RETURN PI() * POW(r, 2);
END //
DELIMITER ; 
