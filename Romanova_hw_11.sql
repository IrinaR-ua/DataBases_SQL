-- 2. Создайте функцию для расчета гипотенузы треугольника, если известны длины его катетов.
-- Используйте формулу 
-- Где:
-- c — длина гипотенузы треугольника,
-- a, b — длины его катетов

DELIMITER //
CREATE FUNCTION hyp_triangle( a DECIMAL, b DECIMAL)
RETURNS DECIMAL(10, 2)
DETERMINISTIC
BEGIN
	RETURN SQRT(POW(a, 2) + POW(b, 2));
END //
DELIMITER ;

